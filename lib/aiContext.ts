import type { CanvasObject } from "./types";

function fmtLabel(text?: string): string {
  if (!text) return "";
  const t = text.trim();
  return t ? t : "";
}

/**
 * Deterministic text generation from structured annotations.
 * No LLM — just a readable summary of what's on the canvas.
 */
export function generateAiContext(objects: CanvasObject[]): string {
  const images = objects.filter((o) => o.type === "image");
  const points = objects
    .filter((o) => o.type === "point")
    .sort((a, b) => (a.number ?? 0) - (b.number ?? 0));
  const texts = objects.filter(
    (o) => o.type === "text" && o.text && o.text.trim().length > 0,
  );
  const arrows = objects.filter((o) => o.type === "arrow");
  const shapes = objects.filter(
    (o) => ["rect", "ellipse", "highlight", "blur"].includes(o.type),
  );

  const labelFor = (pointId: string) =>
    texts.find((t) => t.attachedTo === pointId)?.text?.trim() ?? "";
  const freeTexts = texts.filter((t) => !t.attachedTo);

  const lines: string[] = [];
  lines.push("Visual reference (generated by Point)");
  lines.push("");

  if (images.length > 0) {
    lines.push(`${images.length} image${images.length > 1 ? "s" : ""} on the canvas.`);
    lines.push("");
    images.forEach((img, i) => {
      lines.push(`Image ${i + 1}${img.name ? ` — ${img.name}` : ""}`);
    });
    if (points.length || shapes.length || arrows.length) lines.push("");
  }

  if (points.length > 0) {
    lines.push("Annotations:");
    points.forEach((p) => {
      const num = p.number != null ? `${numToChar(p.number)} ` : "";
      const label = labelFor(p.id);
      lines.push(`- ${num}${label || "(marker)"}`);
    });
    lines.push("");
  }

  if (shapes.length > 0) {
    shapes.forEach((s) => {
      const kind =
        s.type === "rect"
          ? "rectangle region"
          : s.type === "ellipse"
            ? "ellipse region"
            : s.type === "highlight"
              ? "highlighted region"
              : "blurred region";
      lines.push(`- ${kind}`);
    });
    if (shapes.length) lines.push("");
  }

  if (arrows.length > 0) {
    arrows.forEach((a) => {
      const label = fmtLabel(a.text);
      lines.push(`- arrow${label ? ` — "${label}"` : ""}`);
    });
    lines.push("");
  }

  if (freeTexts.length > 0) {
    lines.push("Instructions:");
    freeTexts.forEach((t) => lines.push(`- ${t.text!.trim()}`));
  }

  if (lines.length <= 2) {
    return "Empty canvas — nothing to communicate yet.";
  }

  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}

export function numToChar(n: number): string {
  const chars = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳";
  if (n >= 1 && n <= 20) return chars[n - 1];
  return `${n}`;
}
